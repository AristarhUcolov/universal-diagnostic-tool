// unitName returns a unit symbol in the interface language.
export function unitName(u) {
  return (current === 'ru' && unitsRu[u]) || u || '';
}

// count joins a number with the plural form of the word in key, written
// as "form1|form2[|form5]": "1 code", "2 кода", "5 кодов".
export function count(n, key) {
  const forms = t(key).split('|');
  let i = n === 1 ? 0 : 1;
  if (current === 'ru') {
    const a = Math.abs(n) % 100, b = a % 10;
    i = a > 10 && a < 20 ? 2 : b === 1 ? 0 : b >= 2 && b <= 4 ? 1 : 2;
  }
  return n + ' ' + forms[Math.min(i, forms.length - 1)];
}

// tr picks the current language from a {en, ru} object sent by the backend.
export function tr(text) {
  if (!text) return '';
  if (typeof text === 'string') return text;
  return text[current] || text.en || text.ru || Object.values(text)[0] || '';
}
