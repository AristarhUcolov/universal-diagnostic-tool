//go:build windows

package serial

import (
	"errors"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/sys/windows"
	"golang.org/x/sys/windows/registry"
)

// GUID_DEVCLASS_PORTS: the "Ports (COM & LPT)" device class.
var guidPorts = windows.GUID{Data1: 0x4D36E978, Data2: 0xE325, Data3: 0x11CE,
	Data4: [8]byte{0xBF, 0xC1, 0x08, 0x00, 0x2B, 0xE1, 0x03, 0x18}}

var (
	reVID = regexp.MustCompile(`(?i)VID_([0-9A-F]{4})`)
	rePID = regexp.MustCompile(`(?i)PID_([0-9A-F]{4})`)
)

func listPorts() ([]PortInfo, error) {
	found := map[string]PortInfo{}
	devs, err := windows.SetupDiGetClassDevsEx(&guidPorts, "", 0, windows.DIGCF_PRESENT, 0, "")
	if err == nil {
		for i := 0; ; i++ {
			data, err := devs.EnumDeviceInfo(i)
			if err != nil {
				if errors.Is(err, windows.ERROR_NO_MORE_ITEMS) {
					break
				}
				continue
			}
			pi, ok := describeDevice(devs, data)
			if ok {
				found[pi.Name] = pi
			}
		}
		devs.Close()
	}
	// Ports created by drivers that do not register a device in the
	// Ports class (some Bluetooth stacks, virtual pairs) only appear in
	// SERIALCOMM.
	if k, err := registry.OpenKey(registry.LOCAL_MACHINE, `HARDWARE\DEVICEMAP\SERIALCOMM`, registry.QUERY_VALUE); err == nil {
		names, _ := k.ReadValueNames(-1)
		for _, dev := range names {
			com, _, err := k.GetStringValue(dev)
			if err != nil || com == "" {
				continue
			}
			if _, ok := found[com]; !ok {
				found[com] = PortInfo{Name: com, Description: dev}
			}
		}
		k.Close()
	}
	out := make([]PortInfo, 0, len(found))
	for _, p := range found {
		out = append(out, p)
	}
	sort.Slice(out, func(i, j int) bool { return comNumber(out[i].Name) < comNumber(out[j].Name) })
	return out, nil
}

func describeDevice(devs windows.DevInfo, data *windows.DevInfoData) (PortInfo, bool) {
	key, err := devs.OpenDevRegKey(data, windows.DICS_FLAG_GLOBAL, 0, windows.DIREG_DEV, windows.KEY_READ)
	if err != nil {
		return PortInfo{}, false
	}
	rk := registry.Key(key)
	name, _, err := rk.GetStringValue("PortName")
	rk.Close()
	if err != nil || !strings.HasPrefix(strings.ToUpper(name), "COM") {
		return PortInfo{}, false
	}
	pi := PortInfo{Name: name}
	if v, err := devs.DeviceRegistryProperty(data, windows.SPDRP_FRIENDLYNAME); err == nil {
		pi.Description, _ = v.(string)
	}
	if v, err := devs.DeviceRegistryProperty(data, windows.SPDRP_MFG); err == nil {
		pi.Manufacturer, _ = v.(string)
	}
	var ids []string
	if v, err := devs.DeviceRegistryProperty(data, windows.SPDRP_HARDWAREID); err == nil {
		switch t := v.(type) {
		case []string:
			ids = t
		case string:
			ids = []string{t}
		}
	}
	inst, _ := devs.DeviceInstanceID(data)
	for _, s := range append(ids, inst) {
		if pi.VID == "" {
			if m := reVID.FindStringSubmatch(s); m != nil {
				pi.VID = strings.ToUpper(m[1])
			}
		}
		if pi.PID == "" {
			if m := rePID.FindStringSubmatch(s); m != nil {
				pi.PID = strings.ToUpper(m[1])
			}
		}
	}
	pi.Serial = serialFromInstance(inst)
	return pi, true
}

// serialFromInstance extracts the USB serial number from a device
// instance id such as FTDIBUS\VID_0403+PID_6001+A50285BIA\0000 or
// USB\VID_1A86&PID_7523\5&2B3C1D&0&2 (no serial: generated id).
func serialFromInstance(inst string) string {
	parts := strings.Split(inst, `\`)
	if len(parts) < 3 {
		return ""
	}
	if strings.HasPrefix(strings.ToUpper(parts[0]), "FTDIBUS") {
		plus := strings.Split(parts[1], "+")
		if len(plus) == 3 {
			s := plus[2]
			// FTDI appends the channel letter (A, B...) to the serial.
			if len(s) > 1 {
				s = s[:len(s)-1]
			}
			return s
		}
		return ""
	}
	last := parts[2]
	if strings.Contains(last, "&") {
		return "" // generated by Windows, not a real serial number
	}
	return last
}

func comNumber(name string) int {
	n, err := strconv.Atoi(strings.TrimPrefix(strings.ToUpper(name), "COM"))
	if err != nil {
		return 1 << 20
	}
	return n
}
